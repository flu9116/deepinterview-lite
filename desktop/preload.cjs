const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('interviewDesktop', {
  info: () => ipcRenderer.invoke('recorder:info'),
  serviceSettings: () => ipcRenderer.invoke('services:load'),
  saveServices: input => ipcRenderer.invoke('services:save', input),
  clearServices: () => ipcRenderer.invoke('services:clear'),
  testService: service => ipcRenderer.invoke('services:test', service),
  start: devices => ipcRenderer.invoke('recorder:start', devices),
  append: (id, role, bytes) => ipcRenderer.invoke('recorder:append', id, role, bytes),
  event: (id, type, elapsedMs) => ipcRenderer.invoke('recorder:event', id, type, elapsedMs),
  finish: (id, interrupted) => ipcRenderer.invoke('recorder:finish', id, interrupted),
  list: () => ipcRenderer.invoke('recorder:list'),
  openFolder: () => ipcRenderer.invoke('recorder:open-folder'),
  practice: () => ipcRenderer.invoke('recorder:practice'),
  leavePractice: () => ipcRenderer.invoke('recorder:leave-practice'),
  onPracticeError: callback => ipcRenderer.on('practice:error', (_event, text) => callback(text)),
  profiles: () => ipcRenderer.invoke('profiles:list'),
  importPdf: () => ipcRenderer.invoke('profiles:import'),
  exportPdf: id => ipcRenderer.invoke('profiles:export', id),
  removeProfile: id => ipcRenderer.invoke('profiles:remove', id),
  liveStart: (id, options) => ipcRenderer.invoke('live:start', id, options),
  audio: (id, role, bytes) => ipcRenderer.send('live:audio', id, role, bytes),
  livePause: id => ipcRenderer.invoke('live:pause', id),
  setAsking: (id, value) => ipcRenderer.invoke('live:asking', id, value),
  liveResume: id => ipcRenderer.invoke('live:resume', id),
  reviewLoad: id => ipcRenderer.invoke('review:load', id),
  exportTranscript: id => ipcRenderer.invoke('review:export', id),
  reviewGenerate: id => ipcRenderer.invoke('review:generate', id),
  onLiveEvent: callback => ipcRenderer.on('live:event', (_event, data) => callback(data)),
  onStopRequested: callback => ipcRenderer.on('recorder:stop-requested', () => callback()),
});
